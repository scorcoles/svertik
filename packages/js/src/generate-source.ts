// The text of src/generated.ts, from the engine's registries (see scripts/generate.ts).
import { builtins, effectDescriptions, shapeDescriptions, shapeRegistry, type ParamSpec } from '@svertik/engine';

interface Def { type: string; label: string; kind?: string; params?: Record<string, ParamSpec>; freeParams?: boolean }

/** `vectorgrain` with label "Vector Grain" → `vectorGrain`; the type itself when the label doesn't spell it. */
const NAMES: Record<string, string> = { shapevalues: 'shapeValues' };
export function methodName(type: string, label: string): string {
  if (NAMES[type]) return NAMES[type];
  const words = label.replace(/[^A-Za-z0-9 ]+/g, ' ').trim().split(/\s+/);
  const camel = words.map((w, i) => (i ? w[0]!.toUpperCase() + w.slice(1).toLowerCase() : w.toLowerCase())).join('');
  return camel.toLowerCase() === type ? camel : type;
}
const pascal = (name: string) => name[0]!.toUpperCase() + name.slice(1);

function typeOf(spec: ParamSpec): string {
  switch (spec.type) {
    case 'number': return spec.percentOf ? 'Num | `${number}%`' : 'Num';
    case 'angle': case 'seed': return 'Num';
    case 'point': return '[Num, Num]';
    case 'boolean': return 'boolean';
    case 'enum': return spec.options.map((o) => JSON.stringify(o)).join(' | ');
    case 'color': return 'string';
    case 'palette': return 'string[]';
    case 'node': return 'Ref';
    case 'nodes': return 'Ref[]';
    case 'text': case 'font': return 'string';
    case 'path': return 'unknown[]';
  }
}

function docOf(name: string, spec: ParamSpec): string {
  const bits: string[] = [];
  if (spec.label && spec.label !== name) bits.push(`${spec.label}.`);
  const d = spec.default as unknown;
  if (d !== undefined && !(Array.isArray(d) && d.length > 4) && spec.type !== 'path') bits.push(`Default ${JSON.stringify(d)}.`);
  const range = spec as { min?: number; max?: number; unit?: string };
  if (range.min !== undefined || range.max !== undefined) bits.push(`${range.min ?? '…'} to ${range.max ?? '…'}.`);
  if (range.unit) bits.push(`In ${range.unit === 'fraction' ? 'fractions of the size' : range.unit}.`);
  if (spec.showIf) bits.push(`Only when ${Object.entries(spec.showIf).map(([k, v]) => `${k} is ${v.join(' or ')}`).join(', ')}.`);
  return bits.length ? `  /** ${bits.join(' ').replace(/\*\//g, '* /')} */\n` : '';
}

function paramsInterface(name: string, def: Def, style: boolean): string {
  const lines = Object.entries(def.params ?? {}).map(([k, spec]) => {
    let type = typeOf(spec);
    // `fill: '#fff'` / `stroke: '#000'`: the switch and its colour at once ('none' turns it off).
    if (style && (k === 'fill' || k === 'stroke')) type = 'boolean | string';
    return `${docOf(k, spec)}  ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}?: ${type};`;
  });
  const extra = def.freeParams ? '  [param: string]: unknown;\n' : '';
  return `export interface ${name} {\n${lines.join('\n')}${lines.length ? '\n' : ''}${extra}}\n`;
}

const jsdoc = (text: string | undefined) => (text ? `/** ${text.replace(/\*\//g, '* /').replace(/\s+/g, ' ')} */\n` : '');

export function generate(): string {
  const shapes = [...shapeRegistry.values()] as unknown as Def[];
  const effects = builtins as unknown as Def[];
  const out: string[] = [
    '// Generated by scripts/generate.ts from the engine\'s shapes and effects. Do not edit by hand.',
    "import type { Expr, Var } from './values';",
    "import { Effect, Node, Shape, effect, type EffectRest } from './core';",
    '',
    'type Num = number | Expr | Var;',
    'type Ref = string | Node;',
    '',
  ];

  // Shapes.
  for (const def of shapes) {
    const fn = methodName(def.type, def.label);
    const P = `${pascal(fn)}Params`;
    out.push(paramsInterface(P, def, true));
    out.push(`${jsdoc(shapeDescriptions[def.type] ?? def.label)}export function ${fn}(params?: ${P}): Shape;`);
    out.push(`export function ${fn}(name: string, params?: ${P}): Shape;`);
    out.push(`export function ${fn}(a?: string | ${P}, b?: ${P}): Shape {`);
    out.push(`  return typeof a === 'string' ? new Shape(${JSON.stringify(def.type)}, a, b as Record<string, unknown>) : new Shape(${JSON.stringify(def.type)}, undefined, a as Record<string, unknown>);`);
    out.push('}\n');
  }

  // Effects: a free-standing factory each, and the chain methods.
  const methods: string[] = [];
  const table: string[] = [];
  for (const def of effects) {
    const fn = methodName(def.type, def.label);
    const P = `${pascal(fn)}Params`;
    // Each takes, besides its own Seed, values for every copy (a nested Shape).
    const params = def.type === 'each' ? `${P} & Record<string, unknown>` : P;
    out.push(paramsInterface(P, def, false));
    const doc = jsdoc(`${def.label}${def.kind === 'effector' ? ' (effector: nested effects go after the parameters)' : ''}. ${effectDescriptions[def.type] ?? ''}`.trim());
    out.push(`${doc}export function ${fn}(params?: ${params}, ...rest: EffectRest<${P}>): Effect<${P}>;`);
    out.push(`export function ${fn}(name: string, params?: ${params}, ...rest: EffectRest<${P}>): Effect<${P}>;`);
    out.push(`export function ${fn}(...args: unknown[]): Effect<${P}> { return effect<${P}>(${JSON.stringify(def.type)}, ...(args as [])); }\n`);
    methods.push(`    ${doc.replace(/\n$/, '\n    ')}${fn}(params?: ${params}, ...rest: EffectRest<${P}>): this;`);
    methods.push(`    ${fn}(name: string, params?: ${params}, ...rest: EffectRest<${P}>): this;`);
    table.push(`  ${fn}: ${JSON.stringify(def.type)},`);
  }
  out.push("declare module './core' {");
  out.push('  interface Node {');
  out.push(...methods);
  out.push('  }');
  out.push('}\n');
  out.push('/** Chain method → effect type. */');
  out.push(`export const EFFECT_METHODS = {\n${table.join('\n')}\n} as const;\n`);
  out.push('for (const [method, type] of Object.entries(EFFECT_METHODS)) {');
  out.push('  (Node.prototype as unknown as Record<string, unknown>)[method] = function (this: Node, ...args: unknown[]) { return this.effect(type, ...args); };');
  out.push('}');
  return out.join('\n') + '\n';
}
